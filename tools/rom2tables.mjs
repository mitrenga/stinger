#!/usr/bin/env node
/**
 * rom2tables — extracts the DATA tables of the Stinger program ROM into
 * data/tables.json for app/gameWorker.js (ST-M4).
 *
 * The worker rebuilds a sparse 40 KiB ROM image from them and reads every table
 * 1:1 at its original address, exactly as the original program does. Only data
 * is extracted, never code: the game logic is a hand transcription of the
 * disassembly, so shipping the program image to the browser is both unnecessary
 * and against the decision of 2026-08-30 ("the browser gets tables, not a ROM").
 *
 * The table list, with the note explaining each entry, is tools/rom2tables.spec.json.
 * Bytes are stored base64 — 17 KiB of tables would be five times larger as a JSON
 * array of numbers, and the worker decodes them once at init.
 *
 * usage: node tools/rom2tables.mjs [--spec tools/rom2tables.spec.json] [--out data/tables.json]
 *
 * data/tables.json:
 *   {"rom": "stinger", "sha1": "<program.bin>", "encoding": "base64",
 *    "tables": [{"name", "addr": "0x4200", "len": 256, "note", "data": "..."}]}
 */
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import {fileURLToPath} from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const args = process.argv.slice(2);
const opt = (name, def) => { const i = args.indexOf(name); return i >= 0 ? args[i+1] : def; };

const specFile = path.resolve(ROOT, opt('--spec', 'tools/rom2tables.spec.json'));
const outFile = path.resolve(ROOT, opt('--out', 'data/tables.json'));
const spec = JSON.parse(fs.readFileSync(specFile, 'utf8'));

const romFile = path.resolve(ROOT, spec.rom);
if (!fs.existsSync(romFile)) {
  console.error('missing '+spec.rom+' — run node tools/decrypt-stinger.mjs first (the ROM set stays out of git)');
  process.exit(1);
}
const rom = fs.readFileSync(romFile);
const sha1 = crypto.createHash('sha1').update(rom).digest('hex');

const num = (v) => typeof v === 'number' ? v : parseInt(v, 16);
const hex4 = (n) => '0x'+n.toString(16).toUpperCase().padStart(4, '0');

const tables = [];
let previousEnd = -1;
let total = 0;
for (const entry of spec.tables) {
  const addr = num(entry.from);
  const len = num(entry.len);
  if (addr+len > rom.length) {
    throw new Error(entry.name+': '+hex4(addr)+'+'+len+' is past the end of the ROM ('+rom.length+' bytes)');
  }
  if (addr < previousEnd) {
    throw new Error(entry.name+': starts at '+hex4(addr)+', which overlaps the previous table');
  }
  previousEnd = addr+len;
  total += len;
  tables.push({
    name: entry.name,
    addr: hex4(addr),
    len: len,
    note: entry.note,
    data: Buffer.from(rom.subarray(addr, addr+len)).toString('base64')
  });
}

fs.mkdirSync(path.dirname(outFile), {recursive: true});
fs.writeFileSync(outFile, JSON.stringify({
  rom: 'stinger',
  sha1: sha1,
  encoding: 'base64',
  note: 'Data tables of the program ROM, read by app/gameWorker.js at their original addresses. Generated by tools/rom2tables.mjs from tools/rom2tables.spec.json; no program code is included.',
  tables: tables
}, null, 1));

console.log(path.relative(ROOT, outFile)+': '+tables.length+' tables, '+total+' bytes of ROM ('+
  (total/1024).toFixed(1)+' KiB), file '+(fs.statSync(outFile).size/1024).toFixed(1)+' KiB');
console.log('program.bin sha1 '+sha1);
